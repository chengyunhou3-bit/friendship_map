def language():
    return st.session_state.get("language", "zh")


def t(text):
    if language() != "en" or not isinstance(text, str):
        return text

    exact = ENGLISH_TRANSLATIONS.get(text)
    if exact is not None:
        return exact

    translated = text
    for chinese, english in sorted(
        ENGLISH_TRANSLATIONS.items(),
        key=lambda item: len(item[0]),
        reverse=True
    ):
        translated = translated.replace(chinese, english)
    return translated


def tf(template, **values):
    return t(template).format(**values)
